async function checkRecruitmentNegotiation(page,out){
 // Keep this real acquisition independent of the surrounding desktop career.
 const saved=await page.evaluate(()=>({state:JSON.stringify(state),hub:{...recruitHub},scout:JSON.stringify(scoutDesk)}));
 await page.evaluate(()=>deskNavigate('transfers','search'));
 await page.getByRole('button',{name:'Rensa',exact:true}).click();
 await page.getByRole('searchbox',{name:'Sök kandidater',exact:true}).fill('Daniel Brodin');
 await page.locator('.rd-filters').getByRole('button',{name:'Sök',exact:true}).click();
 await page.locator('.rd-player').filter({hasText:'Daniel Brodin'}).click();
 await page.locator('.rd-inspector').getByRole('button',{name:'Gör förfrågan →',exact:true}).click();
 const modal=page.locator('#recruitment-dialog[open]');
 await modal.getByRole('button',{name:'Kontakta spelare och klubb',exact:true}).click();
 await page.evaluate(()=>{calendarStep(true);calendarStep(true);save();render()});
 const contact=await page.evaluate(()=>scoutingContactKnown(findPlayerAnywhere(recruitHub.player)));
 assert.ok(contact,'real contact becomes available after two calendar days');
 const form=modal.locator('form[data-recruit-player]'),cash=await page.evaluate(()=>state.money);
 await form.locator('input[name=salary]').fill(String(Math.round(contact.salary*.8)));
 await form.locator('select[name=years]').selectOption('2');
 await form.locator('select[name=role]').selectOption(contact.role);
 assert.equal(Number(await form.locator('[data-finance=total]').getAttribute('data-value')),Math.round(contact.salary*.8)*2);
 assert.equal(await page.evaluate(()=>state.money),cash,'editing only previews the transaction');
 await form.getByRole('button',{name:'Skicka köpbud',exact:true}).click();
 assert.equal(await page.locator('dialog[open]').count(),0,'submission opens the selected affair without an obstructing modal');
 const id=await page.evaluate(()=>state.recruitment.deals[0].id);
 await page.evaluate(()=>{calendarStep(true);calendarStep(true);save();render()});
 const inspector=page.locator('.rh-affairs .rh-inspector');
 assert.match(await inspector.locator('.recruit-counter-diff').innerText(),/Årslön/);
 assert.equal(await inspector.getByRole('button',{name:'Acceptera motbud',exact:true}).count(),1);
 await page.screenshot({path:require('node:path').join(out,'recruitment-counter.png'),fullPage:true});
 await inspector.locator('.rh-counter-editor summary').click();
 const revised=inspector.locator('.rh-counter-editor form'),salary=Math.round(contact.salary*.98);
 await revised.locator('input[name=salary]').fill(String(salary));
 await revised.locator('select[name=years]').selectOption('1');
 assert.equal(Number(await revised.locator('[data-finance=total]').getAttribute('data-value')),salary);
 await revised.locator('select[name=years]').selectOption('2');
 const expected=await page.evaluate(({id,salary})=>{const d=state.recruitment.deals.find(d=>d.id===id);return managerCommitmentPreview(findPlayerAnywhere(d.playerId),d.fee,salary,2)},{id,salary});
 for(const key of ['cashAfter','wageAfter','futureAfter','total'])assert.equal(Number(await revised.locator(`[data-finance=${key}]`).getAttribute('data-value')),expected[key],key);
 assert.equal(await page.evaluate(()=>state.money),cash);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),true,'counter form fits the desktop width');
 await revised.getByRole('button',{name:'Skicka reviderat förslag',exact:true}).scrollIntoViewIfNeeded();
 await page.screenshot({path:require('node:path').join(out,'recruitment-revised-proposal.png'),fullPage:true});
 await revised.getByRole('button',{name:'Skicka reviderat förslag',exact:true}).click();
 assert.match(await inspector.innerText(),/Överens om villkoren/);
 assert.equal(await page.evaluate(id=>state.recruitment.deals.find(d=>d.id===id).status,id),'pending');
 const agreement=await page.evaluate(id=>state.recruitment.deals.find(d=>d.id===id).agreement,id);
 assert.equal(agreement.terms.salary,salary);
 await page.reload();
 await page.getByRole('button',{name:/FORTSÄTT KARRIÄR/i}).click();
 await page.evaluate(id=>officeOpenDeal('transfer:'+id),id);
 assert.deepEqual(await page.evaluate(id=>state.recruitment.deals.find(d=>d.id===id).agreement,id),agreement);
 assert.match(await inspector.innerText(),/Överens om villkoren/);
 await page.evaluate(()=>{calendarStep(true);save();render()});
 const registered=await page.evaluate(id=>{const d=state.recruitment.deals.find(d=>d.id===id),p=findPlayerAnywhere(d.playerId);return {status:d.status,salary:p.salary,years:p.contractYears,role:p.promisedRole,club:getPlayerClub(p.id),copies:managerRoster().filter(q=>samePlayerId(q.id,p.id)).length}},id);
 assert.deepEqual(registered,{status:'signed',salary,years:2,role:contact.role,club:'HV71',copies:1});
 assert.equal(await inspector.getByRole('button',{name:'Acceptera motbud',exact:true}).count(),0);
 await page.screenshot({path:require('node:path').join(out,'recruitment-registered.png'),fullPage:true});
 await page.evaluate(saved=>{state=JSON.parse(saved.state);Object.assign(recruitHub,saved.hub);Object.assign(scoutDesk,JSON.parse(saved.scout));save();render()},saved);
}
