'use strict';
const assert=require('node:assert/strict');
async function checkRecruitment(page){
 await page.evaluate(()=>deskNavigate('transfers','overview'));
 const cash=await page.evaluate(()=>state.money),row=page.locator('.rd-table tbody tr[data-recruit-id]').nth(1);
 const id=await row.getAttribute('data-recruit-id');await row.locator('.rd-player').click();
 assert.equal(await page.evaluate(()=>String(recruitHub.player)),id);
 assert.equal(await page.locator('dialog[open]').count(),0,'selection does not launch negotiation');
 await row.getByRole('checkbox').check();
 await page.locator('.rd-table tbody input[type=checkbox]').first().check();
 await page.getByRole('button',{name:/^Jämför \(/}).click();
 await page.locator('#recruitment-dialog[open] .sc-compare').waitFor();
 assert.ok(await page.locator('.sc-compare thead th').count()>=3);
 await page.keyboard.press('Escape');assert.equal(await page.locator('dialog[open]').count(),0);
 assert.equal(await page.evaluate(()=>state.money),cash,'reading/comparison never spends');
 await page.locator('.rd-inspector').getByRole('button',{name:'Bedömning & bevakning →',exact:true}).click();
 await page.locator('#recruitment-dialog[open]').waitFor();
 await page.locator('.rh-inspector-tabs').getByRole('button',{name:'Köp',exact:true}).click();
 await page.locator('input[name=fee]').fill('123456');
 assert.equal(await page.locator('input[name=fee]').inputValue(),'123456');
 await page.keyboard.press('Escape');
 await page.locator('.rd-profile').click();assert.equal(await page.evaluate(()=>state.page),'marketPlayer');
 await page.evaluate(()=>deskBack());assert.equal(await page.evaluate(()=>String(recruitHub.player)),id);
 await page.evaluate(()=>deskNavigate('transfers','search'));
 await page.getByRole('button',{name:/^Filter/}).click();
 await page.getByRole('combobox',{name:'Spelarprofil',exact:true}).selectOption('Målvakt');
 assert.equal(await page.locator('#recruitment-dialog[open]').count(),1,'filter rerender preserves modal');
 await page.getByRole('button',{name:'Visa kandidater',exact:true}).click();
 assert.equal(await page.evaluate(()=>recruitmentCandidates('search').every(p=>p.pos==='MV')),true);
 await page.getByRole('button',{name:'Rensa',exact:true}).click();
 const name=await page.locator('.rd-player').nth(2).innerText();await page.getByRole('searchbox',{name:'Sök kandidater',exact:true}).fill(name);
 await page.locator('.rd-filters').getByRole('button',{name:'Sök',exact:true}).click();
 assert.equal(await page.locator('.rd-player').count(),1);
 await page.locator('.rd-player').click();await page.locator('.rd-profile').click();await page.evaluate(()=>deskBack());
 assert.equal(await page.getByRole('searchbox',{name:'Sök kandidater',exact:true}).inputValue(),name);
 await page.getByRole('button',{name:'Rensa',exact:true}).click();
 await page.getByRole('combobox',{name:'Rekryteringsväg',exact:true}).selectOption('own');
 const own=await page.evaluate(()=>String(recruitHub.player));
 await page.locator('.rd-inspector').getByRole('button',{name:'Lån ut',exact:true}).click();
 assert.equal(await page.locator('#recruitment-dialog[open]').count(),1);
 assert.equal(await page.evaluate(()=>String(recruitHub.player)),own);
 await page.keyboard.press('Escape');
 await page.getByRole('combobox',{name:'Rekryteringsväg',exact:true}).selectOption('all');
 await page.evaluate(()=>deskNavigate('transfers','overview'));
}
module.exports={checkRecruitment};
