'use strict';
// Reproducible offline runtime snapshot. Raw Europe imports remain untouched.
const fs=require('node:fs'),zlib=require('node:zlib');
const catalog=require('../data/europe/catalog.json');
const pack=JSON.parse(zlib.gunzipSync(fs.readFileSync('data/europe/players.json.gz')));
const corrections={
 'nationalleague:345020':{exclude:true,source:'https://lausannehc.ch/2026/09/14/le-lhc-et-sami-niku-se-separent-dun-commun-accord-2/',reason:'Club announced departure on 2026-09-14'}
};
const positions={
 'nationalleague:327657':{position:'F',source:'https://www.sihf.ch/de/game-center/team/spielerstatistiken/117-4-103570'},
 'nationalleague:352058':{position:'F',source:'https://www.sihf.ch/fr/game-center/game/composition/20271105000028'}
};
const clubs=catalog.clubs.filter(c=>c.league==='CH_NL').map(c=>({id:c.id,name:c.name,code:c.code,crest:c.crest.file}));
const players=pack.players.filter(p=>p.association.league==='CH_NL'&&!p.association.removed&&!corrections[p.id]?.exclude).map(p=>({id:p.id,name:p.name,birth:p.birth,position:positions[p.id]?.position||p.position,nationality:p.nationality,clubId:p.association.clubId,attributes:p.estimate?.attributes||null,potential:p.estimate?.potential||null,stats:p.stats,source:p.sources[0].url}));
// Missing positions are excluded, never inferred from names or assigned at random.
const excluded=players.filter(p=>!p.position).map(p=>({id:p.id,name:p.name,reason:'Position not supplied by source'}));
const value={version:'ch-career-1',checked:pack.checked,clubs,positions,players:players.filter(p=>p.position),corrections,excluded};
const content='"use strict";\n// Generated by scripts/build-swiss-data.cjs. See qa/swiss-career.md.\nconst SWISS_DATABASE='+JSON.stringify(value)+';\n';
if(process.argv.includes('--check')){if(fs.readFileSync('swiss-data.js','utf8')!==content)throw Error('Stale Swiss runtime data');}
else fs.writeFileSync('swiss-data.js',content);
console.log(JSON.stringify({clubs:clubs.length,players:value.players.length,excluded}));
