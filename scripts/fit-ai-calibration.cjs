'use strict';
// Fit only the declared training clubs. Validation snapshots are never read.
// Joint geometry representatives preserve distance/angle/pressure correlations.
const fs=require('node:fs'),path=require('node:path');
const dir=process.argv[2],out=process.argv[3];
if(!dir||!out)throw Error('Usage: node scripts/fit-ai-calibration.cjs samples output.js');
const groups={},exposure={},ids=[],powerplays=[];
const manifest=JSON.parse(fs.readFileSync(path.join(__dirname,'../qa/ai-calibration-specs.json'),'utf8'));
for(const spec of manifest.filter(s=>s.phase==='train')){
 const name=spec.id+'.json';
 const r=JSON.parse(fs.readFileSync(path.join(dir,name),'utf8'));
 if(r.spec.phase!=='train')continue;ids.push(r.spec.id);
 for(let side=0;side<2;side++){
  const p=r.plans[side],key=p.style+':'+p.shotChoice,ppKey='pp:'+p.pp+':'+r.plans[1-side].pk;
  for(const s of r.live[side].strength){if(s.kind==='pp'&&s.seconds>0)powerplays.push({key:ppKey,style:p.style,choice:p.shotChoice,hours:s.seconds/3600,attempts:s.attempts});if(r.spec.purpose==='overloadDiamond'&&s.kind!=='pp')continue;const k=s.kind==='even'?key:s.kind==='pp'?ppKey:p.style+':pk';const x=exposure[k]??={seconds:0,attempts:0};x.seconds+=s.seconds;x.attempts+=s.attempts;}
 }
 for(const s of r.measured){
  if(s.context.rebound||s.context.behind)continue;
  const p=r.plans[s.side],kind=s.side===0||s.situation==='even'?s.situation:s.situation==='pp'?'pk':'pp';
  if(r.spec.purpose==='overloadDiamond'&&kind!=='pp')continue;
  const key=kind==='even'?p.style+':'+p.shotChoice:kind==='pp'?'pp:'+p.pp+':'+r.plans[1-s.side].pk:kind;
  (groups[key]??=[]).push({...s.context,block:s.block});
 }
}
if(ids.length!==174)throw Error('Training must contain exactly 174 predeclared fixtures, got '+ids.length);
const geometry={};
for(const [key,shots] of Object.entries(groups)){
 shots.sort((a,b)=>a.d-b.d);const count=Math.min(16,Math.floor(shots.length/4)),bins=[];
 for(let i=0;i<count;i++){
  const rows=shots.slice(Math.floor(i*shots.length/count),Math.floor((i+1)*shots.length/count));
  bins.push(['d','angle','pressure','screen','lateralSpeed','block'].map(k=>+ (rows.reduce((n,r)=>n+r[k],0)/rows.length).toFixed(4)));
 }
 geometry[key]={attempts:shots.length,bins};
}
const attempts=Object.fromEntries(Object.entries(exposure).map(([k,v])=>[k,+ (v.attempts*3600/v.seconds).toFixed(3)]));
// Poisson exposure fit separates formation matchups from tactical shot utility.
// Small neutral priors stabilize sparse style/choice cells; validation is absent.
const ppModifiers={style:{control:1,counter:1,pressure:1},shotChoice:{balanced:1,patient:1,shoot:1}};
const observedAttemptsPer60={...attempts};
for(let iteration=0;iteration<100;iteration++){
 for(const key of Object.keys(attempts).filter(k=>k.startsWith('pp:'))){
  const rows=powerplays.filter(r=>r.key===key);
  attempts[key]=(rows.reduce((n,r)=>n+r.attempts,0)+observedAttemptsPer60[key]*.05)/(rows.reduce((n,r)=>n+r.hours*ppModifiers.style[r.style]*ppModifiers.shotChoice[r.choice],0)+.05);
 }
 for(const [field,factors] of [['style',ppModifiers.style],['choice',ppModifiers.shotChoice]])for(const key of Object.keys(factors)){
  const rows=powerplays.filter(r=>r[field]===key);
  factors[key]=(rows.reduce((n,r)=>n+r.attempts,0)+8)/(rows.reduce((n,r)=>n+r.hours*attempts[r.key]*(field==='style'?ppModifiers.shotChoice[r.choice]:ppModifiers.style[r.style]),0)+8);
 }
}
const normalization=ppModifiers.style.control*ppModifiers.shotChoice.balanced;
for(const key of Object.keys(attempts).filter(k=>k.startsWith('pp:')))attempts[key]=+(attempts[key]*normalization).toFixed(5);
for(const factors of [ppModifiers.style,ppModifiers.shotChoice]){const base=factors.control??factors.balanced;for(const key of Object.keys(factors))factors[key]=+(factors[key]/base).toFixed(5);}
const data={version:1,ppModifiers,observedAttemptsPer60,trainingFixtures:ids.sort((a,b)=>a-b),columns:['distance','angle','pressure','screen','lateralSpeed','block'],attemptsPer60:attempts,geometry};
fs.writeFileSync(out,'"use strict";\n// Generated by scripts/fit-ai-calibration.cjs from training fixtures only.\n// Estimated joint shot geometry, never coordinates from a background rink.\nconst AI_CALIBRATION = '+JSON.stringify(data,null,1)+';\n');
console.log(JSON.stringify({training:ids.length,attempts}));
