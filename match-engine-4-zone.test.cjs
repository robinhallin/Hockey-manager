const offsideCarry=carry.value,offsideDump=dump.value;
mates[0].x=36;mates[1].x=37;rows=m.actionOptions(a);carry=rows.find(r=>r.kind==='carry');dump=rows.find(r=>r.kind==='dump');
assert.ok(carry.value>offsideCarry,'an onside rush makes controlled entry more attractive');
assert.ok(dump.value<offsideDump,'with onside support the engine does not force the same dump');
