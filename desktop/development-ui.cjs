 await page.getByRole('heading',{name:'Världen',exact:true}).waitFor();
 assert.equal(await main.locator('[aria-current="true"]').innerText(),'Världen');
 await page.screenshot({path:path.join(out,'23-varlden.png'),fullPage:true});
 await page.locator('.desk-subnav').getByRole('button',{name:'Landslag & JVM',exact:true}).click();
